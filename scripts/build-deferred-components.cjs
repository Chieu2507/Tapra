const output = '/* Generated by scripts/build-deferred-components.cjs. Edit component assets, then rebuild. */\n' + files.map(file => `/* ${file} */\n${fs.readFileSync(file, 'utf8')}`).join('\n');
const { spawnSync } = require('node:child_process');
const result = spawnSync(process.argv[2] || 'esbuild', ['--loader=css', '--minify', '--legal-comments=inline'], { input: output, encoding: 'utf8' });
if (result.error || result.status !== 0) {
  throw result.error || new Error(result.stderr);
}
fs.writeFileSync('assets/deferred-template-components.css', result.stdout);
console.log('Built deferred-template-components.css:', Buffer.byteLength(result.stdout), 'bytes');
